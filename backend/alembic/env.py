"""
alembic/env.py
=================

WHY THIS FILE EXISTS
---------------------
Alembic needs to know two things to do its job: which database to connect
to, and what the "target" schema should look like (so it can diff that
against the real database and autogenerate a migration). This file is
where those two things are wired to the actual app, instead of the
Alembic-generated boilerplate's placeholder values.

WHAT PROBLEM IT SOLVES
------------------------
By default, `alembic init` generates a `sqlalchemy.url` placeholder in
`alembic.ini` and an empty `target_metadata = None` in `env.py`. Left as-is,
`alembic revision --autogenerate` has nothing to compare against and would
generate an empty migration. This file points Alembic at
`settings.database_url` (so it always matches whatever the app itself
connects to — no separate, driftable config) and at `Base.metadata` (the
registry every ORM model in `db/models.py` registers itself into).

HOW IT WORKS INTERNALLY
--------------------------
Alembic supports two migration modes: "online" (connects to the DB and
runs DDL directly — used for `alembic upgrade head`) and "offline"
(just prints the SQL that *would* run, without a live connection — useful
for generating a `.sql` file to hand to a DBA). Both code paths are kept
here (as generated), but both are repointed at `settings.database_url`
instead of reading from `alembic.ini`'s static placeholder, and both use
`target_metadata = Base.metadata` so `--autogenerate` can see our five
tables and two ENUM types.

WHY THIS IMPLEMENTATION (vs alternatives)
--------------------------------------------
- Reading the DB URL from `app.config.settings` (chosen): one source of
  truth — the same `DATABASE_URL` environment variable used by the running
  app is used by Alembic, so migrations can never accidentally target a
  different database than the app itself connects to.
- Leaving the DB URL hard-coded in `alembic.ini` (the generated default):
  works, but now you have two places to update `DATABASE_URL` and they can
  silently drift apart between environments.

DISCUSSION / DEFENSE QUESTIONS
--------------------------------
Q: "What does --autogenerate actually do?"
A: It inspects the live database's current schema, compares it column-by-
   column against `target_metadata` (built from our ORM models), and
   writes a migration script containing the `op.create_table` / `op.
   add_column` / etc. calls needed to make the DB match the models.

Q: "Why must you still manually review an autogenerated migration?"
A: Autogenerate can't always detect everything correctly — it's known to
   sometimes miss `ondelete=` cascade behavior on foreign keys and doesn't
   know the ordering constraint that ENUM types must be created before any
   table that uses them. `02-database-schema.md` calls this out explicitly
   as a required manual verification step.

COMMON STUDENT MISTAKES
--------------------------
- Editing the live database schema by hand "just this once" — from that
  point on, Alembic's model of "current DB state" no longer matches
  reality, and every future autogenerate is unreliable.
- Forgetting to run `alembic upgrade head` after pulling a teammate's new
  migration file — the file existing in git doesn't apply it.
"""

from logging.config import fileConfig

from sqlalchemy import engine_from_config, pool

from alembic import context
from app.config import settings
from app.db import models  # noqa: F401 — import so models register on Base.metadata
from app.db.base import Base

config = context.config
config.set_main_option("sqlalchemy.url", settings.database_url)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
