"""initial schema

Revision ID: 0001_initial_schema
Revises:
Create Date: 2026-07-17

WHY THIS FILE EXISTS
---------------------
This is the migration that turns an empty Postgres database into the
NutriLens schema — the two ENUM types, and the five tables (`user`,
`meal_log`, `food_item`, `meal_item`, `recommendation`) with their
indexes and foreign keys, exactly as designed in `02-database-schema.md`.
Running `alembic upgrade head` with only this migration present is what
M1's Definition of Done means by "migration creates the schema exactly as
02".

WHAT PROBLEM IT SOLVES
------------------------
The ORM models in `db/models.py` describe the *desired* schema in Python;
they do nothing to an actual database until a migration applies them.
Alembic migrations are how "the code changed" becomes "the database
changed", in a versioned, repeatable, team-shareable way (unlike hand-run
`CREATE TABLE` statements, which nobody else's environment would replay).

HOW IT WORKS INTERNALLY
--------------------------
`upgrade()` runs top-to-bottom when applying this migration;
`downgrade()` reverses it (used for rollback). Order matters a lot here:
Postgres ENUM types (`health_goal_enum`, `meal_type_enum`) must exist
*before* any table references them as a column type — this migration
creates both enums first, exactly the manual-verification point that
`02-database-schema.md §4` warns autogenerate sometimes gets wrong. Tables
are then created in dependency order: `user` and `food_item` have no
foreign keys and go first; `meal_log` depends on `user`; `meal_item`
depends on both `meal_log` and `food_item`; `recommendation` depends on
`user`. Every `sa.ForeignKey(...)` explicitly repeats the `ondelete=`
value from the schema design so the *database itself* (not just the ORM)
enforces the cascade/restrict policy — this is the second manual-
verification point the schema doc calls out.

WHY THIS IMPLEMENTATION (vs alternatives)
--------------------------------------------
- One hand-verified migration for the whole initial schema (chosen): for
  a brand-new project this is clearer to review end-to-end than several
  small autogenerated migrations layered on top of each other, and lets
  us guarantee enum-before-table ordering and correct `ondelete=` values
  by inspection rather than trusting the autogenerate diff blindly.
- Running `alembic revision --autogenerate` against a running Postgres
  instance and using its output verbatim: this is the normal workflow
  after M1 (for every *subsequent* schema change), but the very first
  migration is written explicitly here so the reasoning above is visible
  and auditable in one place, matching what a supervisor will ask about
  in the defense.

DISCUSSION / DEFENSE QUESTIONS
--------------------------------
Q: "Why do the ENUM types get created before any table?"
A: `CREATE TABLE ... column health_goal_enum` requires the type
   `health_goal_enum` to already exist in Postgres's type catalogue —
   creating it after the table would fail with `type "health_goal_enum"
   does not exist`.

Q: "Why does meal_item -> food_item use RESTRICT but user -> meal_log
    uses CASCADE?"
A: `food_item` is shared reference data (the USDA cache) — deleting one
   user's meal item must never be allowed to delete a food row other
   users' meal items still reference. `meal_log`/`meal_item` are *owned*
   exclusively by one user, so cascading their deletion when the user is
   deleted (FR14) is exactly the desired behavior.

Q: "What would `alembic downgrade -1` do here?"
A: Drop all five tables, then drop both ENUM types — fully reversing this
   migration back to an empty database. Table drop order in `downgrade()`
   is the reverse of creation order to respect FK dependencies.

COMMON STUDENT MISTAKES
--------------------------
- Creating tables before their referenced ENUM type exists (ordering bug).
- Forgetting `sa.Enum(..., create_type=False)` when a column reuses an
  enum type already created by `sa.Enum(...).create(...)` earlier in the
  same migration — omitting this causes Alembic to try to CREATE TYPE
  twice and fail on the second table.
- Dropping tables in downgrade() in creation order instead of reverse
  order, which fails on FK constraints still pointing at not-yet-dropped
  tables.
"""

from collections.abc import Sequence

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql

from alembic import op

revision: str = "0001_initial_schema"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def upgrade() -> None:
    # --- 1. ENUM types first (must exist before any table uses them) ---
    health_goal_enum = postgresql.ENUM(
        "weight_loss", "maintenance", "weight_gain", name="health_goal_enum"
    )
    meal_type_enum = postgresql.ENUM("breakfast", "lunch", "dinner", "snack", name="meal_type_enum")
    health_goal_enum.create(op.get_bind(), checkfirst=True)
    meal_type_enum.create(op.get_bind(), checkfirst=True)

    # --- 2. user ---
    op.create_table(
        "user",
        sa.Column("user_id", sa.Integer(), primary_key=True),
        sa.Column("username", sa.String(50), nullable=False, unique=True),
        sa.Column("email", sa.String(100), nullable=False, unique=True),
        sa.Column("password_hash", sa.String(255), nullable=False),
        sa.Column(
            "health_goal",
            # postgresql.ENUM honours create_type=False (the generic sa.Enum does
            # NOT) — so the type created once above is reused, not re-created.
            postgresql.ENUM(
                "weight_loss",
                "maintenance",
                "weight_gain",
                name="health_goal_enum",
                create_type=False,
            ),
            nullable=False,
        ),
        sa.Column("created_at", sa.TIMESTAMP(), server_default=sa.func.now(), nullable=False),
        sa.Column("account_locked", sa.Boolean(), nullable=False, server_default=sa.false()),
        sa.Column("failed_login_count", sa.SmallInteger(), nullable=False, server_default="0"),
    )
    op.create_index("idx_user_email", "user", ["email"])

    # --- 3. food_item (shared reference table, no FKs) ---
    op.create_table(
        "food_item",
        sa.Column("food_id", sa.Integer(), primary_key=True),
        sa.Column("usda_fdc_id", sa.String(20), unique=True, nullable=True),
        sa.Column("food_name", sa.String(200), nullable=False),
        sa.Column("food101_class", sa.String(50), nullable=True),
        sa.Column("calories_per_100g", sa.Numeric(7, 2), nullable=True),
        sa.Column("protein_per_100g", sa.Numeric(7, 2), nullable=True),
        sa.Column("carbs_per_100g", sa.Numeric(7, 2), nullable=True),
        sa.Column("fat_per_100g", sa.Numeric(7, 2), nullable=True),
        sa.Column("cooking_method", sa.String(30), nullable=True),
        sa.Column("cached_at", sa.TIMESTAMP(), server_default=sa.func.now(), nullable=False),
    )
    op.create_index("idx_food_item_class", "food_item", ["food101_class"])
    op.create_index(
        "idx_food_item_class_method",
        "food_item",
        ["food101_class", "cooking_method"],
        unique=True,
    )

    # --- 4. meal_log (depends on user) ---
    op.create_table(
        "meal_log",
        sa.Column("log_id", sa.Integer(), primary_key=True),
        sa.Column(
            "user_id",
            sa.Integer(),
            sa.ForeignKey("user.user_id", ondelete="CASCADE"),
            nullable=False,
        ),
        sa.Column("logged_at", sa.TIMESTAMP(), server_default=sa.func.now(), nullable=False),
        sa.Column(
            "meal_type",
            postgresql.ENUM(
                "breakfast",
                "lunch",
                "dinner",
                "snack",
                name="meal_type_enum",
                create_type=False,
            ),
            nullable=False,
        ),
        sa.Column("total_calories", sa.Numeric(7, 2), nullable=True),
        sa.Column("user_confirmed", sa.Boolean(), nullable=False, server_default=sa.false()),
    )
    op.create_index("idx_meal_log_user", "meal_log", ["user_id"])
    op.create_index("idx_meal_log_user_time", "meal_log", ["user_id", sa.text("logged_at DESC")])

    # --- 5. meal_item (depends on meal_log, food_item) ---
    op.create_table(
        "meal_item",
        sa.Column("item_id", sa.Integer(), primary_key=True),
        sa.Column(
            "log_id",
            sa.Integer(),
            sa.ForeignKey("meal_log.log_id", ondelete="CASCADE"),
            nullable=False,
        ),
        sa.Column(
            "food_id",
            sa.Integer(),
            sa.ForeignKey("food_item.food_id", ondelete="RESTRICT"),
            nullable=False,
        ),
        sa.Column("portion_min_g", sa.Numeric(6, 1), nullable=True),
        sa.Column("portion_max_g", sa.Numeric(6, 1), nullable=True),
        sa.Column("portion_confirmed_g", sa.Numeric(6, 1), nullable=True),
        sa.Column("confidence_score", sa.Float(), nullable=True),
        sa.Column("calories_est", sa.Numeric(7, 2), nullable=True),
        sa.Column("protein_est_g", sa.Numeric(7, 2), nullable=True),
        sa.Column("carbs_est_g", sa.Numeric(7, 2), nullable=True),
        sa.Column("fat_est_g", sa.Numeric(7, 2), nullable=True),
    )
    op.create_index("idx_meal_item_log", "meal_item", ["log_id"])

    # --- 6. recommendation (depends on user) ---
    op.create_table(
        "recommendation",
        sa.Column("rec_id", sa.Integer(), primary_key=True),
        sa.Column(
            "user_id",
            sa.Integer(),
            sa.ForeignKey("user.user_id", ondelete="CASCADE"),
            nullable=False,
        ),
        sa.Column("generated_at", sa.TIMESTAMP(), server_default=sa.func.now(), nullable=False),
        sa.Column("insight_text", sa.Text(), nullable=False),
        sa.Column("nutrient_focus", sa.String(30), nullable=True),
        sa.Column("was_read", sa.Boolean(), nullable=False, server_default=sa.false()),
    )
    op.create_index(
        "idx_recommendation_user",
        "recommendation",
        ["user_id", sa.text("generated_at DESC")],
    )


def downgrade() -> None:
    # Reverse order: drop dependents before what they depend on.
    op.drop_table("recommendation")
    op.drop_table("meal_item")
    op.drop_table("meal_log")
    op.drop_table("food_item")
    op.drop_table("user")

    postgresql.ENUM(name="meal_type_enum").drop(op.get_bind(), checkfirst=True)
    postgresql.ENUM(name="health_goal_enum").drop(op.get_bind(), checkfirst=True)
